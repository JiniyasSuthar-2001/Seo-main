class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that adds professional running header and footer with total page count (Page X of Y)
    and executive branding rules.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(PDFColors.MUTED_TEXT)

        page_width, page_height = self._pagesize

        # Running Header on page 2 and later
        if self._pageNumber > 1:
            self.setFillColor(PDFColors.MUTED_TEXT)
            self.drawString(36, page_height - 24, "SEO INTELLIGENCE PLATFORM — EXECUTIVE AUDIT REPORT")
            self.drawRightString(page_width - 36, page_height - 24, datetime.now().strftime("%B %d, %Y"))
            self.setStrokeColor(PDFColors.BORDER_LIGHT)
            self.setLineWidth(0.75)
            self.line(36, page_height - 28, page_width - 36, page_height - 28)

        # Running Footer on all pages
        self.setStrokeColor(PDFColors.BORDER_LIGHT)
        self.setLineWidth(0.75)
        self.line(36, 32, page_width - 36, 32)

        self.setFillColor(PDFColors.MUTED_TEXT)
        self.drawString(36, 20, "Confidential — Generated by SEO Intelligence Platform")
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(page_width - 36, 20, page_str)

        self.restoreState()


