    def _get_health_color_hex(self, score: int) -> str:
        if score >= 85:
            return "#10b981"
        elif score >= 60:
            return "#f59e0b"
        return "#ef4444"

    def build_kpi_grid(self, story: list, kpis: List[Dict[str, Any]]):
        """
        Builds a 4-column executive KPI card grid with high-contrast metric values and color status indicators.
        """
        rows = []
        # Chunk into rows of 4
        chunk_size = 4
        for i in range(0, len(kpis), chunk_size):
            chunk = kpis[i:i + chunk_size]
            row_cells = []
            for item in chunk:
                title = item.get("title", "METRIC").upper()
                value = str(item.get("value", "0"))
                subtext = item.get("subtext", "")
                val_color = item.get("color", "#0f172a")

                val_style = ParagraphStyle(
                    f'ValStyle_{title}_{i}',
                    parent=self.theme.kpi_value,
                    textColor=colors.HexColor(val_color) if isinstance(val_color, str) and val_color.startswith("#") else val_color
                )

                card_content = [
                    Paragraph(title, self.theme.kpi_title),
                    Spacer(1, 2),
                    Paragraph(value, val_style),
                    Spacer(1, 2),
                    Paragraph(subtext, self.theme.kpi_sub)
                ]
                row_cells.append(card_content)

            # Pad row if less than 4
            while len(row_cells) < 4:
                row_cells.append([Paragraph("", self.theme.body)])

            rows.append(row_cells)

        t_kpi = Table(rows, colWidths=[135, 135, 135, 135])
        t_kpi.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), PDFColors.BG_CARD),
            ('BOX', (0, 0), (-1, -1), 0.75, PDFColors.BORDER_MED),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, PDFColors.BORDER_LIGHT),
            ('PADDING', (0, 0), (-1, -1), 7),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ]))
        story.append(t_kpi)
        story.append(Spacer(1, 12))

    def build_vector_issue_chart(self, crit: int, warn: int, notice: int, passed: int) -> Drawing:
        """
        Creates a native vector chart visualizing the issue & audit distribution.
        """
        d = Drawing(540, 110)
        # Background container
        d.add(Rect(0, 0, 540, 110, fillColor=PDFColors.BG_CARD, strokeColor=PDFColors.BORDER_LIGHT, strokeWidth=0.5, rx=6, ry=6))

        # Title
        d.add(String(16, 90, "AUDIT FINDINGS DISTRIBUTION", fontName="Helvetica-Bold", fontSize=9, fillColor=PDFColors.MUTED_TEXT))

        # Total issues count
        total = crit + warn + notice + passed
        if total == 0:
            total = 1

        # Vector Horizontal Multi-Segment Progress Bar
        bar_x = 16
        bar_y = 55
        bar_w = 508
        bar_h = 22

        # Draw background bar
        d.add(Rect(bar_x, bar_y, bar_w, bar_h, fillColor=PDFColors.BORDER_LIGHT, strokeColor=None, rx=4, ry=4))

        crit_w = (crit / total) * bar_w
        warn_w = (warn / total) * bar_w
        notice_w = (notice / total) * bar_w
        passed_w = (passed / total) * bar_w

        curr_x = bar_x
        if crit_w > 0:
            d.add(Rect(curr_x, bar_y, crit_w, bar_h, fillColor=PDFColors.CRITICAL_RED, strokeColor=None))
            curr_x += crit_w
        if warn_w > 0:
            d.add(Rect(curr_x, bar_y, warn_w, bar_h, fillColor=PDFColors.WARNING_AMBER, strokeColor=None))
            curr_x += warn_w
        if notice_w > 0:
            d.add(Rect(curr_x, bar_y, notice_w, bar_h, fillColor=PDFColors.INFO_BLUE, strokeColor=None))
            curr_x += notice_w
        if passed_w > 0:
            d.add(Rect(curr_x, bar_y, passed_w, bar_h, fillColor=PDFColors.SUCCESS_GREEN, strokeColor=None))

        # Legend items at bottom
        leg_y = 20
        # Critical
        d.add(Circle(22, leg_y + 4, 4, fillColor=PDFColors.CRITICAL_RED, strokeColor=None))
        d.add(String(32, leg_y, f"Critical Issues: {crit}", fontName="Helvetica-Bold", fontSize=8, fillColor=PDFColors.PRIMARY_DARK))

        # Warning
        d.add(Circle(160, leg_y + 4, 4, fillColor=PDFColors.WARNING_AMBER, strokeColor=None))
        d.add(String(170, leg_y, f"Warnings: {warn}", fontName="Helvetica-Bold", fontSize=8, fillColor=PDFColors.PRIMARY_DARK))

        # Notices
        d.add(Circle(285, leg_y + 4, 4, fillColor=PDFColors.INFO_BLUE, strokeColor=None))
        d.add(String(295, leg_y, f"Notices / Info: {notice}", fontName="Helvetica-Bold", fontSize=8, fillColor=PDFColors.PRIMARY_DARK))

        # Passed
        d.add(Circle(410, leg_y + 4, 4, fillColor=PDFColors.SUCCESS_GREEN, strokeColor=None))
        d.add(String(420, leg_y, f"Passed Checks: {passed}", fontName="Helvetica-Bold", fontSize=8, fillColor=PDFColors.PRIMARY_DARK))

        return d

    def build_issue_card(self, story: list, idx: int, issue: Dict[str, Any]):
        """
        Creates an executive issue card with severity badge pill, affected URL, evidence, why it matters, and AI solutions.
        """
        sev = str(issue.get("severity") or issue.get("priority") or "Warning").upper()
        if sev in ("CRITICAL", "FATAL", "ERROR"):
            badge_bg = PDFColors.CRITICAL_RED_BG
            badge_color = PDFColors.CRITICAL_RED_DARK
            border_color = PDFColors.CRITICAL_RED
        elif sev in ("HIGH", "WARNING", "MEDIUM"):
            badge_bg = PDFColors.WARNING_AMBER_BG
            badge_color = PDFColors.WARNING_AMBER_DARK
            border_color = PDFColors.WARNING_AMBER
        else:
            badge_bg = PDFColors.INFO_BLUE_BG
            badge_color = PDFColors.INFO_BLUE
            border_color = PDFColors.INFO_BLUE

        prob_title = html.escape(str(issue.get("problem") or issue.get("title") or issue.get("issue") or "Detected SEO Issue"))
        url = html.escape(str(issue.get("affected_url") or issue.get("url") or "-"))
        found = html.escape(str(issue.get("what_was_found") or issue.get("evidence") or issue.get("description") or "Identified during crawl inspection."))
        why = html.escape(str(issue.get("why_it_matters") or "Impacts search engine crawl efficiency, content indexability, or keyword ranking relevance."))
        action = html.escape(str(issue.get("recommended_action") or issue.get("recommendation") or "Review and resolve affected page element."))
        ai_sol = html.escape(str(issue.get("ai_solution") or action or "Deploy targeted on-page metadata and structural fixes."))

        badge_p = Paragraph(f"<font color='{badge_color.hexval()}'><b>{sev}</b></font>", self.theme.table_header)
        title_p = Paragraph(f"<b>{idx}. {prob_title}</b>", self.theme.issue_header)

        header_table = Table([[title_p, badge_p]], colWidths=[460, 60])
        header_table.setStyle(TableStyle([
            ('ALIGN', (1, 0), (1, 0), 'RIGHT'),
            ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
            ('PADDING', (0, 0), (-1, -1), 0),
        ]))

        content_rows = [
            [header_table],
            [HRFlowable(width="100%", thickness=0.5, color=PDFColors.BORDER_LIGHT, spaceAfter=4, spaceBefore=4)],
            [Paragraph(f"<b>Affected URL:</b> <font color='#2563eb'>{url}</font>", self.theme.issue_text)],
            [Paragraph(f"<b>What We Found:</b> {found}", self.theme.issue_text)],
            [Paragraph(f"<b>Why It Matters:</b> {why}", self.theme.issue_text)],
            [Paragraph(f"<b>Recommended Action:</b> {action}", self.theme.issue_text)],
            [Paragraph(f"<b>AI Action Plan:</b> <font color='#2563eb'>{ai_sol}</font> <i>(Evidence Grounded)</i>", self.theme.ai_recommendation)]
        ]

        t_card = Table(content_rows, colWidths=[520])
        t_card.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), PDFColors.BG_CARD),
            ('BOX', (0, 0), (-1, -1), 0.75, border_color),
            ('PADDING', (0, 0), (-1, -1), 6),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ]))

        story.append(t_card)
        story.append(Spacer(1, 7))

    def build_styled_table(self, headers: List[str], rows: List[List[Any]], col_widths: List[float], max_rows: int = 50) -> Table:
        """
        Creates an executive styled table with crisp borders, shaded header, and alternating rows.
        """
        table_data = [[Paragraph(f"<b>{h}</b>", self.theme.table_header) for h in headers]]

        display_rows = rows[:max_rows] if max_rows else rows
        for row in display_rows:
            formatted_row = []
            for cell in row:
                if isinstance(cell, Paragraph):
                    formatted_row.append(cell)
                else:
                    formatted_row.append(Paragraph(html.escape(str(cell if cell is not None else "-")), self.theme.table_cell))
            table_data.append(formatted_row)

        t = Table(table_data, colWidths=col_widths)
        t.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), PDFColors.BG_CARD_ALT),
            ('GRID', (0, 0), (-1, -1), 0.5, PDFColors.BORDER_LIGHT),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [PDFColors.WHITE, PDFColors.BG_CARD]),
            ('PADDING', (0, 0), (-1, -1), 4.5),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ]))
        return t

